// Prototype jetable : les quatre styles visuels à comparer.
// Tout est dessiné dans le code, sans aucun fichier d'image ni de modèle.

export type Finish = 'pixel' | 'wood' | 'paper' | 'neon' | 'toon' | 'clay' | 'soft';

export type ColorKey =
  | 'ground'
  | 'path'
  | 'wood'
  | 'counter'
  | 'awningA'
  | 'awningB'
  | 'sign'
  | 'can'
  | 'candy1'
  | 'candy2'
  | 'candy3'
  | 'fenceA'
  | 'fenceB'
  | 'ghost'
  | 'skin'
  | 'shirt'
  | 'trousers'
  | 'hat'
  | 'pole';

export interface Style {
  finish: Finish;
  label: string;
  description: string;
  skyTop: number;
  skyBottom: number;
  hemisphere: { sky: number; ground: number; intensity: number };
  sun: { color: number; intensity: number };
  /** Force du halo lumineux ; 0 = pas de halo. */
  bloom: number;
  /** Multiplicateur de luminosité des ampoules (au-dessus de 1, elles rayonnent). */
  bulbBoost: number;
  /** Liseré autour des volumes : épaisseur, et couleur fixe ou couleur du volume. */
  rim: { thickness: number; color: number | 'own'; boost: number } | null;
  /** Arrondi des blocs : part de la plus petite dimension, et plafond. null = arêtes vives. */
  round: { ratio: number; max: number } | null;
  /** Formes rondes (ballons en boule, boîtes en cylindre) à la place de certains blocs. */
  curves: boolean;
  /** Nombre de tons d'ombre du cel shading (fini « toon » seulement). */
  toonBands?: 2 | 3;
  ghostOpacity: number;
  stars: boolean;
  colors: Record<ColorKey, number>;
  bulbs: number[];
}

